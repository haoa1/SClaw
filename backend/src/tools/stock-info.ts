// stock-info.ts provides getStocks() — stock data loading from disk cache

const EM_API = "https://push2.eastmoney.com/api/qt/ulist.np/get";
const CACHE_TTL = 30000;
let cache: { data: any[]; time: number } | null = null;

const FIELDS = "f2,f3,f5,f6,f8,f9,f12,f14,f15,f16,f17,f18";

function convertCode(code: string): string {
  if (code.startsWith("6") || code.startsWith("9")) return "1." + code;
  return "0." + code;
}

function parseEMData(json: any): any[] {
  const stocks: any[] = [];
  const items = json?.data?.diff || [];
  for (const item of items) {
    try {
      const code = String(item.f12 || "");
      const name = String(item.f14 || "");
      if (!code || !name) continue;

      const price = item.f2 || 0;
      const changePct = item.f3 !== undefined ? item.f3 : 0;
      const high = item.f15 || 0;
      const low = item.f16 || 0;
      const openPrice = item.f17 || 0;
      const close = item.f18 || 0;
      const volume = item.f5 || 0;
      const amount = item.f6 || 0;
      const pe = item.f9 || 0;
      const turnover = item.f8 !== undefined ? item.f8 : 0;

      stocks.push({
        code, name,
        market: code.startsWith("6") ? "SH" : "SZ",
        price, open: openPrice, high, low, close,
        changePct: parseFloat(changePct.toFixed(2)),
        volume, amount,
        turnover: parseFloat(turnover.toFixed(2)),
        pe: parseFloat(pe.toFixed(2)), pb: 0, marketCap: 0,
      });
    } catch {}
  }
  return stocks;
}

export async function getStocks(): Promise<any[]> {
  if (cache && Date.now() - cache.time < CACHE_TTL) return cache.data;
  try {
    const allData: any[] = [];
    const chunkSize = 200;
    for (let i = 0; i < ALL_CODES.length; i += chunkSize) {
      const chunk = ALL_CODES.slice(i, i + chunkSize);
      const secids = chunk.map(convertCode).join(",");
      const url = EM_API + "?fltt=2&fields=" + FIELDS + "&secids=" + secids;
      const res = await fetch(url, {
        headers: { "User-Agent": "Mozilla/5.0", "Referer": "https://quote.eastmoney.com/" }
      });
      const json = await res.json();
      allData.push(...parseEMData(json));
    }
    cache = { data: allData, time: Date.now() };
    return allData;
  } catch {
    if (cache) return cache.data;
    return [];
  }
}

